# Задача 2.4. Моржовый оператор (базово)
# ============================================================
# Условие:
#   Запросите строку. Если её длина больше 5, выведите
#   длину строки. Используйте моржовый оператор :=,
#   чтобы не вызывать len() дважды.
#
# Пример:
#   In: hello world
#   Out: 11
#
#   In: hi
#   Out: (ничего)
#
# Подсказка:
#   if (n := len(s)) > 5:
#       print(n)

def task_2_4(s: str) -> int | None:
    if (n := len(s)) > 5:
        return n
    return None


# ============================================================
# Задача 2.5. Моржовый оператор в цикле
# ============================================================
# Условие:
#   Считывайте строки с клавиатуры, пока не введено "stop".
#   Выводите каждую строку с префиксом "-> ".
#   Используйте моржовый оператор в условии while.
#
# Пример:
#   In: a
#   In: b
#   In: stop
#   Out: -> a
#        -> b
#
# Подсказка:
#   while (line := input()) != "stop":
#       print(f"-> {line}")

def task_2_5():
    while (line := input()) != "stop":
        print("->", line)


